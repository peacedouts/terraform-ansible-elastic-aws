#!/usr/bin/env bash
# Creates ansible/inventory/group_vars/all/vault.yml with random secrets and
# encrypts it with Ansible Vault. The plaintext never touches disk: it is
# piped straight into `ansible-vault encrypt`.
#
# Usage: scripts/generate-vault.sh [--force]
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
vault_file="${repo_root}/ansible/inventory/group_vars/all/vault.yml"

if [[ -e "${vault_file}" && "${1:-}" != "--force" ]]; then
  echo "error: ${vault_file} already exists. Use --force to replace it (the old secrets are lost)." >&2
  exit 1
fi

command -v ansible-vault >/dev/null || { echo "error: ansible-vault not found" >&2; exit 1; }
command -v openssl >/dev/null || { echo "error: openssl not found" >&2; exit 1; }

# 32 random URL-safe characters: no quotes or shell metacharacters to escape.
rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-32}"; }

umask 077
{
  echo "---"
  echo "# Generated by scripts/generate-vault.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  for name in \
    vault_elastic_password \
    vault_kibana_system_password \
    vault_logstash_system_password \
    vault_beats_system_password \
    vault_remote_monitoring_user_password \
    vault_logstash_writer_password \
    vault_metricbeat_writer_password \
    vault_logstash_keystore_password; do
    echo "${name}: \"$(rand 32)\""
  done
  for name in \
    vault_kibana_security_encryption_key \
    vault_kibana_saved_objects_encryption_key \
    vault_kibana_reporting_encryption_key; do
    echo "${name}: \"$(rand 48)\""
  done
} | ansible-vault encrypt --output "${vault_file}" -

echo "Wrote encrypted ${vault_file}"
echo "View it with: ansible-vault view ${vault_file}"
